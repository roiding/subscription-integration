import { randomBytes, createHash, randomUUID } from "node:crypto";
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { createInterface } from "node:readline/promises";
import { stdin as input, stdout as output } from "node:process";
import path from "node:path";

const cwd = process.cwd();
const templatePath = path.join(cwd, "wrangler.toml.example");
const configPath = path.join(cwd, "wrangler.toml");
const devVarsPath = path.join(cwd, ".dev.vars");

const rl = createInterface({ input, output });

try {
  ensureTemplateExists();
  runChecked("npx", ["wrangler", "whoami"], "Wrangler login check failed. Run `npx wrangler login` first.");

  const workerName = await ask("Worker name", "subscription-integration");
  const databaseName = await ask("D1 database name", "v2ray_subscription_db");
  const upstreamUrl = await ask("Default upstream URL (optional)", "");
  const tokenMode = await ask("Token mode: shared or split", "shared");
  const shouldDeploy = (await ask("Deploy automatically after bootstrap? (yes/no)", "yes")).toLowerCase() !== "no";

  const databaseId = createRemoteDatabase(databaseName);
  writeWranglerConfig(workerName, databaseName, databaseId);
  runChecked("npm", ["run", "db:migrate:remote"], "Failed to apply remote D1 migrations.");

  const tokens = createBootstrapTokens(tokenMode === "split" ? "split" : "shared");
  insertBootstrapTokens(databaseName, tokens);
  writeDevVars(workerName, databaseName, tokens);

  if (upstreamUrl) {
    putSecret("UPSTREAM_RULESET_URL", upstreamUrl);
  }

  if (shouldDeploy) {
    runChecked("npx", ["wrangler", "deploy"], "Automatic deploy failed.");
  }

  printSummary({ workerName, databaseName, databaseId, tokens, upstreamUrl, shouldDeploy });
} finally {
  rl.close();
}

function ensureTemplateExists() {
  if (!existsSync(templatePath)) {
    throw new Error(`Missing template: ${templatePath}`);
  }
}

async function ask(label, defaultValue) {
  const suffix = defaultValue ? ` [${defaultValue}]` : "";
  const answer = (await rl.question(`${label}${suffix}: `)).trim();
  return answer || defaultValue;
}

function runChecked(command, args, errorMessage, options = {}) {
  const result = spawnSync(command, args, {
    cwd,
    encoding: "utf8",
    stdio: ["pipe", "pipe", "pipe"],
    input: options.input
  });

  if (result.status !== 0) {
    const outputText = [result.stdout, result.stderr].filter(Boolean).join("\n");
    throw new Error(`${errorMessage}\n\n${outputText}`.trim());
  }

  return [result.stdout, result.stderr].filter(Boolean).join("\n");
}

function createRemoteDatabase(databaseName) {
  const outputText = runChecked(
    "npx",
    ["wrangler", "d1", "create", databaseName, "--json"],
    "Failed to create the remote D1 database."
  );

  try {
    const parsed = JSON.parse(outputText);
    return parsed.uuid || parsed.database_id || parsed.id;
  } catch {
    const match = outputText.match(/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/i);
    if (match) {
      return match[0];
    }
  }

  throw new Error(`Unable to detect database ID from wrangler output:\n\n${outputText}`);
}

function writeWranglerConfig(workerName, databaseName, databaseId) {
  const template = readFileSync(templatePath, "utf8");
  const config = template
    .replace('name = "your-worker-name"', `name = "${workerName}"`)
    .replace('database_name = "your-d1-database-name"', `database_name = "${databaseName}"`)
    .replace('database_id = "replace-with-your-d1-database-id"', `database_id = "${databaseId}"`);
  writeFileSync(configPath, config, "utf8");
}

function createBootstrapTokens(mode) {
  const shared = createTokenRecord("bootstrap-shared-token", ["admin:*", "subscriptions:read"]);
  if (mode === "shared") {
    return [shared];
  }
  return [
    createTokenRecord("bootstrap-admin-token", ["admin:*"]),
    createTokenRecord("bootstrap-subscription-token", ["subscriptions:read"])
  ];
}

function createTokenRecord(name, scopes) {
  const plaintext = randomBytes(32).toString("hex");
  const tokenSha256 = createHash("sha256").update(plaintext).digest("hex");
  return {
    id: randomUUID(),
    name,
    plaintext,
    tokenSha256,
    scopes,
    enabled: true,
    notes: `${name} generated by bootstrap-cloudflare.mjs`,
    createdAt: new Date().toISOString(),
    updatedAt: new Date().toISOString()
  };
}

function insertBootstrapTokens(databaseName, tokens) {
  const statements = tokens.map((token) => {
    const scopesSql = `json_array(${token.scopes.map((scope) => `'${scope.replace(/'/g, "''")}'`).join(", ")})`;
    return `INSERT INTO admin_tokens (id, name, token_sha256, scopes_json, enabled, notes, created_at, updated_at) VALUES ('${token.id}', '${escapeSql(token.name)}', '${token.tokenSha256}', ${scopesSql}, 1, '${escapeSql(token.notes)}', '${token.createdAt}', '${token.updatedAt}')`;
  });
  runChecked(
    "npx",
    ["wrangler", "d1", "execute", databaseName, "--remote", "--command", statements.join("; ") + ";"],
    "Failed to insert bootstrap tokens into D1."
  );
}

function putSecret(name, value) {
  runChecked(
    "npx",
    ["wrangler", "secret", "put", name],
    `Failed to store secret ${name}.`,
    { input: `${value}\n` }
  );
}

function writeDevVars(workerName, databaseName, tokens) {
  const lines = [
    "# Generated by npm run cf:bootstrap",
    `WORKER_NAME=\"${workerName}\"`,
    `WORKER_DATABASE_NAME=\"${databaseName}\"`
  ];

  for (const token of tokens) {
    const baseName = token.name.toUpperCase().replace(/[^A-Z0-9]+/g, "_");
    lines.push(`${baseName}=\"${token.plaintext}\"`);
    lines.push(`${baseName}_SHA256=\"${token.tokenSha256}\"`);
  }

  writeFileSync(devVarsPath, `${lines.join("\n")}\n`, "utf8");
}

function printSummary({ workerName, databaseName, databaseId, tokens, upstreamUrl, shouldDeploy }) {
  const summary = [
    "\nBootstrap complete.",
    `Worker: ${workerName}`,
    `D1 Database: ${databaseName}`,
    `Database ID: ${databaseId}`,
    `Default upstream: ${upstreamUrl || "not set"}`,
    `Deploy run: ${shouldDeploy ? "yes" : "no"}`,
    "",
    "Generated plaintext tokens were written to .dev.vars:"
  ];

  for (const token of tokens) {
    summary.push(`- ${token.name}: ${token.plaintext}`);
  }

  summary.push("", "Open /admin and use the admin token to continue.");
  console.log(summary.join("\n"));
}

function escapeSql(value) {
  return String(value).replace(/'/g, "''");
}
